import { PrismaClient, SectorArea, RequirementType } from "@prisma/client";

const prisma = new PrismaClient();

type RequirementInput = {
  type: RequirementType;
  requiredLevel?: number;
  itemName: string;
  sortOrder: number;
};

type CollectionInput = {
  identifier: string;
  stars: number;
  area: SectorArea;
  name: string; // English name (used for all locales for now)
  requirements: RequirementInput[];
};

function animal(level: number, name: string, sortOrder: number): RequirementInput {
  return { type: "ANIMAL", requiredLevel: level, itemName: name, sortOrder };
}

function decoration(name: string, sortOrder: number): RequirementInput {
  return { type: "DECORATION", itemName: name, sortOrder };
}


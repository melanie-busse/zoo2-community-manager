async function main() {
  console.log("Seeding collections...");

  for (const col of collections) {
    const created = await prisma.collection.upsert({
      where: { identifier: col.identifier },
      update: {},
      create: {
        identifier: col.identifier,
        stars: col.stars,
        area: col.area,
        texts: {
          create: [
            { languageCode: "de", name: col.name },
            { languageCode: "en", name: col.name },
            { languageCode: "da", name: col.name },
            { languageCode: "nl", name: col.name },
            { languageCode: "es", name: col.name },
            { languageCode: "fr", name: col.name },
          ],
        },
        requirements: {
          create: col.requirements.map((r) => ({
            type: r.type,
            requiredLevel: r.requiredLevel ?? null,
            itemName: r.itemName,
            sortOrder: r.sortOrder,
          })),
        },
      },
    });
    console.log(`  ✓ ${created.identifier}`);
  }

  console.log(`Done. Seeded ${collections.length} collections.`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
